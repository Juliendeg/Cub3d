#include "libft.h"

int	ft_putnbr(int n)
{
	int	x;

	x = 0;
	if (n == -2147483648)
	{
		write(1, "-2147483648", 11);
		return (x + 11);
	}
	if (n < 0)
	{
		x = x + ft_putchar('-');
		n = -n;
	}
	if (n > 9)
		x = x + ft_putnbr(n / 10);
	x = x + ft_putchar(n % 10 + '0');
	return (x);
}
