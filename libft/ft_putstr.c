#include "libft.h"

int	ft_putstr(char *str)
{
	int	i;

	i = 0;
	if (!str)
		i = i + ft_putstr("(null)");
	else
	{
		while (str[i])
			i++;
		write(1, str, i);
	}
	return (i);
}
