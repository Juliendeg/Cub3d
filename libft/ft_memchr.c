#include "libft.h"

void	*ft_memchr(const void *s, int c, size_t n)
{
	const char	*s2;
	size_t		i;

	s2 = (const char *)s;
	i = 0;
	while (i < n)
	{
		if (s2[i] == (const char)c)
			return ((void *)&s2[i]);
		i++;
	}
	return (NULL);
}
