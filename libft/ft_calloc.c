#include "libft.h"

void	*ft_calloc(size_t nmemb, size_t size)
{
	void	*table;

	if ((nmemb == SIZE_MAX) || (size == SIZE_MAX))
		return (NULL);
	table = malloc(nmemb * size);
	if (!table)
		return (NULL);
	ft_bzero(table, nmemb * size);
	return (table);
}
